"""Pydantic v2 Schemas for Communication, Notifications, Announcements & Messaging."""

from typing import List, Optional, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field, ConfigDict
from app.models.communication import (
    NotificationCategory,
    NotificationPriority,
    NotificationStatus,
    AnnouncementScope,
    AnnouncementStatus,
    AnnouncementPriority,
    ConversationType,
)


# -------------------------------------------------------------
# NOTIFICATION SCHEMAS
# -------------------------------------------------------------
class NotificationCreate(BaseModel):
    recipient_id: str
    category: NotificationCategory = NotificationCategory.ACADEMIC
    priority: NotificationPriority = NotificationPriority.NORMAL
    title: str = Field(..., max_length=200)
    message: str
    source_type: Optional[str] = None
    source_id: Optional[str] = None
    action_url: Optional[str] = None
    dedup_key: Optional[str] = None


class NotificationResponse(BaseModel):
    id: str
    recipient_id: str
    category: NotificationCategory
    priority: NotificationPriority
    status: NotificationStatus
    title: str
    message: str
    source_type: Optional[str] = None
    source_id: Optional[str] = None
    action_url: Optional[str] = None
    read_at: Optional[datetime] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class NotificationPreferenceResponse(BaseModel):
    user_id: str
    email_enabled: bool
    academic_alerts: bool
    assignment_reminders: bool
    exam_notifications: bool
    result_notifications: bool
    announcements_enabled: bool
    ai_insights_enabled: bool

    model_config = ConfigDict(from_attributes=True)


class NotificationPreferenceUpdate(BaseModel):
    email_enabled: Optional[bool] = None
    academic_alerts: Optional[bool] = None
    assignment_reminders: Optional[bool] = None
    exam_notifications: Optional[bool] = None
    result_notifications: Optional[bool] = None
    announcements_enabled: Optional[bool] = None
    ai_insights_enabled: Optional[bool] = None


class UnreadCountResponse(BaseModel):
    unread_notifications_count: int
    unread_messages_count: int


# -------------------------------------------------------------
# ANNOUNCEMENT SCHEMAS
# -------------------------------------------------------------
class AnnouncementCreate(BaseModel):
    title: str = Field(..., max_length=255)
    content: str
    scope_type: AnnouncementScope = AnnouncementScope.COURSE
    scope_id: Optional[str] = None
    priority: AnnouncementPriority = AnnouncementPriority.NORMAL
    is_acknowledgement_required: bool = False
    publish_now: bool = True
    expires_at: Optional[datetime] = None


class AnnouncementUpdate(BaseModel):
    title: Optional[str] = Field(None, max_length=255)
    content: Optional[str] = None
    priority: Optional[AnnouncementPriority] = None
    is_acknowledgement_required: Optional[bool] = None
    expires_at: Optional[datetime] = None


class AnnouncementResponse(BaseModel):
    id: str
    title: str
    content: str
    author_id: str
    author_name: str
    author_role: str
    scope_type: AnnouncementScope
    scope_id: Optional[str] = None
    scope_name: Optional[str] = None
    priority: AnnouncementPriority
    status: AnnouncementStatus
    is_acknowledgement_required: bool
    is_acknowledged: bool = False
    total_acknowledgements: int = 0
    publish_at: datetime
    expires_at: Optional[datetime] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class AnnouncementAcknowledgementResponse(BaseModel):
    announcement_id: str
    user_id: str
    acknowledged_at: datetime


class AIDraftRequest(BaseModel):
    topic_or_purpose: str
    audience: str  # "STUDENTS", "FACULTY", "DEPARTMENT", "INSTITUTION"
    key_points: List[str] = []
    tone: Optional[str] = "Professional and Academic"


class AIDraftResponse(BaseModel):
    draft_title: str
    draft_content: str
    is_ai_generated: bool
    safety_disclaimer: str = "This draft is generated by AI. Review and edit before official publication."


class AISummarizeRequest(BaseModel):
    content: str
    max_words: Optional[int] = 100


class AISummarizeResponse(BaseModel):
    summary: str
    key_takeaways: List[str] = []
    is_ai_generated: bool
    safety_disclaimer: str = "AI-generated summary for quick preview. Consult official full announcement text."


class AIToneImproveRequest(BaseModel):
    text: str
    desired_tone: Optional[str] = "Polite, Clear, and Authoritative Academic"


class AIToneImproveResponse(BaseModel):
    improved_text: str
    is_ai_generated: bool
    safety_disclaimer: str = "AI-suggested revision. Ensure content matches institutional guidelines."


# -------------------------------------------------------------
# ACADEMIC MESSAGING SCHEMAS
# -------------------------------------------------------------
class ConversationCreate(BaseModel):
    participant_user_id: str
    course_id: Optional[str] = None
    title: Optional[str] = None
    initial_message: Optional[str] = None


class DirectMessageCreate(BaseModel):
    body: str = Field(..., min_length=1, max_length=5000)


class DirectMessageResponse(BaseModel):
    id: str
    conversation_id: str
    sender_id: str
    sender_name: str
    sender_role: str
    body: str
    is_edited: bool
    is_deleted: bool
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ConversationParticipantResponse(BaseModel):
    user_id: str
    user_name: str
    user_email: str
    user_role: str
    last_read_at: datetime


class ConversationResponse(BaseModel):
    id: str
    title: Optional[str] = None
    conversation_type: ConversationType
    course_id: Optional[str] = None
    course_name: Optional[str] = None
    created_by: str
    participants: List[ConversationParticipantResponse] = []
    last_message: Optional[DirectMessageResponse] = None
    unread_messages_count: int = 0
    updated_at: datetime
